#!/usr/bin/env python3
"""Generate the built-in workout presets from Software/Libs/score/presets.json.

Usage: .venv/bin/python3 -I tools/gen_presets.py [--check]

presets.json is one array; list order = id order (1..N) = order on the watch:

  [ { "name": "Around the World S",
      "steps": [ { "spot": "LCorner3", "goal": "attempts", "value": 10, "rest": 15 }, ... ] },
    ... ]

  spot   a score::Spot enumerator name (Spots.hpp)
  goal   attempts | makes | time
  value  1..999 (shots, or seconds for time)
  rest   0..255 seconds after the step

Validated: 1..99 presets (ids stay below the user-workout range); name 1..19 bytes (UTF-8) and unique; 1..8 steps; spot and goal known;
value and rest in range; volume (sum of attempts and makes values) <= 400 (kMaxShots). An attempts
value above 50 only warns: the GUI then draws a progress ring instead of a segmented one.

Writes Software/Libs/score/Presets.hpp (kPresetCount) and Presets.cpp (the kPresets table).
--check regenerates in memory and exits 1 if either committed file differs. The output is
deterministic (no timestamps). Standard library only; paths are relative to the repository
root (the parent of tools/).
"""

import difflib
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SCORE = ROOT / "Software" / "Libs" / "score"
SOURCE = SCORE / "presets.json"
HPP = SCORE / "Presets.hpp"
CPP = SCORE / "Presets.cpp"

# score::Spot enumerators, in enum order (Spots.hpp).
SPOTS = (
    "LCorner3", "LWing3", "Top3", "RWing3", "RCorner3",
    "LBaselineMid", "LElbowMid", "TopKeyMid", "RElbowMid", "RBaselineMid",
    "Ft", "LayupL", "LayupR",
)
GOALS = {"attempts": "Attempts", "makes": "Makes", "time": "Time"}

MAX_PRESETS = 99      # preset ids are 1..N; user workouts start at 100 (kFirstUserWorkoutId)
MAX_NAME_BYTES = 19   # kNameLen 20 incl. NUL
MAX_STEPS = 8         # kMaxSteps
MAX_VALUE = 999
MAX_REST = 255        # Step::rest_s is uint8_t
MAX_SHOTS = 400       # kMaxShots
MAX_SEGMENTS = 50     # Ring::kMaxSegments

STEP_KEYS = {"spot", "goal", "value", "rest"}
PRESET_KEYS = {"name", "steps"}

HEADER = "// GENERATED by tools/gen_presets.py from presets.json — do not edit.\n"


class PresetError(Exception):
    pass


def is_int(v):
    return isinstance(v, int) and not isinstance(v, bool)


def validate(data):
    """Return the warnings; raise PresetError on the first error."""
    warnings = []
    if not isinstance(data, list) or not 1 <= len(data) <= MAX_PRESETS:
        raise PresetError(f"top level must be an array of 1..{MAX_PRESETS} presets")
    names = set()
    for i, p in enumerate(data, start=1):
        where = f"preset {i}"
        if not isinstance(p, dict) or set(p) != PRESET_KEYS:
            raise PresetError(f"{where}: must be an object with exactly the keys {sorted(PRESET_KEYS)}")
        name = p["name"]
        if not isinstance(name, str):
            raise PresetError(f"{where}: name must be a string")
        where = f"preset {i} ({name!r})"
        size = len(name.encode("utf-8"))
        if not 1 <= size <= MAX_NAME_BYTES:
            raise PresetError(f"{where}: name is {size} bytes, must be 1..{MAX_NAME_BYTES}")
        if any(ord(c) < 0x20 or ord(c) == 0x7F for c in name):
            raise PresetError(f"{where}: name contains a control character")
        if name in names:
            raise PresetError(f"{where}: duplicate name")
        names.add(name)
        steps = p["steps"]
        if not isinstance(steps, list) or not 1 <= len(steps) <= MAX_STEPS:
            raise PresetError(f"{where}: steps must be an array of 1..{MAX_STEPS} steps")
        volume = 0
        for j, s in enumerate(steps, start=1):
            at = f"{where} step {j}"
            if not isinstance(s, dict) or set(s) != STEP_KEYS:
                raise PresetError(f"{at}: must be an object with exactly the keys {sorted(STEP_KEYS)}")
            if s["spot"] not in SPOTS:
                raise PresetError(f"{at}: unknown spot {s['spot']!r} (known: {', '.join(SPOTS)})")
            if s["goal"] not in GOALS:
                raise PresetError(f"{at}: unknown goal {s['goal']!r} (known: {', '.join(GOALS)})")
            if not is_int(s["value"]) or not 1 <= s["value"] <= MAX_VALUE:
                raise PresetError(f"{at}: value {s['value']!r} must be an integer 1..{MAX_VALUE}")
            if not is_int(s["rest"]) or not 0 <= s["rest"] <= MAX_REST:
                raise PresetError(f"{at}: rest {s['rest']!r} must be an integer 0..{MAX_REST}")
            if s["goal"] != "time":
                volume += s["value"]
            if s["goal"] == "attempts" and s["value"] > MAX_SEGMENTS:
                warnings.append(f"{at}: {s['value']} attempts > {MAX_SEGMENTS}, "
                                "progress ring instead of segments")
        if volume > MAX_SHOTS:
            raise PresetError(f"{where}: volume {volume} shots > {MAX_SHOTS}")
    return warnings


def c_string(text):
    """A C string literal; non-ASCII bytes as 3-digit octal escapes (no run-on like \\x)."""
    out = []
    for b in text.encode("utf-8"):
        if b in (0x22, 0x5C):
            out.append("\\" + chr(b))
        elif 0x20 <= b < 0x7F:
            out.append(chr(b))
        else:
            out.append(f"\\{b:03o}")
    return '"' + "".join(out) + '"'


def render_hpp(data):
    return (
        HEADER
        + "\n"
        "#pragma once\n"
        "\n"
        "#include <cstdint>\n"
        "\n"
        "namespace score {\n"
        f"constexpr uint8_t kPresetCount = {len(data)};\n"
        "} // namespace score\n"
    )


def render_cpp(data):
    lines = [
        HEADER.rstrip("\n"),
        "",
        '#include "score/Workout.hpp"',
        '#include "score/PresetsTable.hpp"',
        "",
        "namespace score {",
        "",
        "const Workout kPresets[kPresetCount] = {",
    ]
    for i, p in enumerate(data, start=1):
        lines.append(f"    {{ {i}, {c_string(p['name'])}, {len(p['steps'])}, {{")
        for s in p["steps"]:
            lines.append(f"        step(Spot::{s['spot']}, GoalType::{GOALS[s['goal']]}, "
                         f"{s['value']}, {s['rest']}),")
        lines.append("    } },")
    lines += ["};", "", "} // namespace score", ""]
    return "\n".join(lines)


def main(argv):
    check = argv[1:] == ["--check"]
    if argv[1:] and not check:
        print(__doc__.strip().splitlines()[2], file=sys.stderr)
        return 2
    try:
        data = json.loads(SOURCE.read_text(encoding="utf-8"))
        warnings = validate(data)
    except (OSError, ValueError, PresetError) as e:
        print(f"gen_presets: {SOURCE.relative_to(ROOT)}: {e}", file=sys.stderr)
        return 1
    for w in warnings:
        print(f"gen_presets: warning: {w}", file=sys.stderr)

    outputs = {HPP: render_hpp(data), CPP: render_cpp(data)}
    if check:
        stale = False
        for path, text in outputs.items():
            old = path.read_text(encoding="utf-8") if path.exists() else ""
            if old != text:
                stale = True
                rel = str(path.relative_to(ROOT))
                sys.stderr.writelines(difflib.unified_diff(
                    old.splitlines(keepends=True), text.splitlines(keepends=True),
                    fromfile=f"{rel} (committed)", tofile=f"{rel} (generated)"))
        if stale:
            print("gen_presets: stale output; run tools/gen_presets.py", file=sys.stderr)
            return 1
        print(f"gen_presets: up to date ({len(data)} presets)")
        return 0

    for path, text in outputs.items():
        with open(path, "w", encoding="utf-8", newline="\n") as f:
            f.write(text)
    print(f"gen_presets: wrote {HPP.relative_to(ROOT)}, {CPP.relative_to(ROOT)} ({len(data)} presets)")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
